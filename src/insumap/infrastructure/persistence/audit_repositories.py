"""Audit reads over PostgreSQL, under the row level security of the transaction.

Newest first by identifier: the identifiers are UUIDv7 generated by the database,
so their order follows the time of the insert. ``page.after`` is the last
identifier of the previous page; the next page continues below it.
"""

from __future__ import annotations

from typing import Any, Final, final, override
from uuid import UUID

from sqlalchemy import Select, select, text

from insumap.application.access.ports import (
    AccessPurpose,
    DataAccessOutcome,
    DataResource,
)
from insumap.application.audit.ports import (
    AuditChainPort,
    AuditLogFilter,
    AuditLogReadPort,
    AuditLogRow,
    DataAccessFilter,
    DataAccessReadPort,
    DataAccessRow,
    SecurityEventFilter,
    SecurityEventKind,
    SecurityEventReadPort,
    SecurityEventRow,
)
from insumap.application.common.pagination import Page, PageRequest, build_page
from insumap.application.security.events import SecuritySeverity
from insumap.infrastructure.persistence.orm import (
    AuditLogOrm,
    DataAccessLogOrm,
    SecurityEventOrm,
)
from insumap.infrastructure.persistence.transactions import CurrentSession

FIRST_BROKEN_ROW: Final = text(
    "SELECT broken_id FROM audit.verify_chain(CAST(:clinic_id AS uuid))"
)
"""``audit.verify_chain`` returns no row when the chain is intact, one otherwise."""


def _newest_first(statement: Select[Any], page: PageRequest, orm: Any) -> Select[Any]:
    """Keyset page of ``orm`` rows, newest first, after ``page.after``."""
    if page.after is not None:
        statement = statement.where(orm.id < page.after)
    return statement.order_by(orm.id.desc()).limit(page.limit + 1)


def _ip(value: Any) -> str | None:
    """The truncated address as text; the driver may return an address object."""
    return None if value is None else str(value)


@final
class AuditLogReadRepository(AuditLogReadPort):
    """``audit.audit_log``: only the clinic admin of the clinic reads it (RLS-5)."""

    def __init__(self, current: CurrentSession) -> None:
        self._current = current

    @override
    def list(
        self, clinic_id: UUID, filters: AuditLogFilter, page: PageRequest
    ) -> Page[AuditLogRow]:
        statement = select(AuditLogOrm).where(AuditLogOrm.clinic_id == clinic_id)
        if filters.user_id is not None:
            statement = statement.where(AuditLogOrm.actor_user_id == filters.user_id)
        if filters.action is not None:
            statement = statement.where(AuditLogOrm.action == filters.action)
        if filters.occurred_from is not None:
            statement = statement.where(
                AuditLogOrm.occurred_at >= filters.occurred_from
            )
        if filters.occurred_to is not None:
            statement = statement.where(AuditLogOrm.occurred_at <= filters.occurred_to)
        rows = (
            self._current.get()
            .scalars(_newest_first(statement, page, AuditLogOrm))
            .all()
        )
        return build_page(
            [_audit_row(row) for row in rows], limit=page.limit, key=lambda r: r.id
        )


def _audit_row(row: AuditLogOrm) -> AuditLogRow:
    return AuditLogRow(
        id=row.id,
        occurred_at=row.occurred_at,
        actor_user_id=row.actor_user_id,
        actor_role=row.actor_role,
        action=row.action,
        entity_type=row.entity_type,
        entity_id=row.entity_id,
        reason=row.reason,
        changed_fields=tuple(row.changed_fields),
    )


