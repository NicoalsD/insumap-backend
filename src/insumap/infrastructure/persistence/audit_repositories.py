@final
class SecurityEventReadRepository(SecurityEventReadPort):
    """``iam.security_events``; RLS limits a clinic admin to its own clinic.

    The clinic filter of the scope is applied as well, so the query never relies
    on the policy alone.
    """

    def __init__(self, current: CurrentSession) -> None:
        self._current = current

    @override
    def list(
        self, filters: SecurityEventFilter, page: PageRequest
    ) -> Page[SecurityEventRow]:
        statement = select(SecurityEventOrm)
        if filters.clinic_id is not None:
            statement = statement.where(SecurityEventOrm.clinic_id == filters.clinic_id)
        if filters.event_type is not None:
            statement = statement.where(
                SecurityEventOrm.event_type == filters.event_type.value
            )
        if filters.severity is not None:
            statement = statement.where(
                SecurityEventOrm.severity == filters.severity.value
            )
        if filters.occurred_from is not None:
            statement = statement.where(
                SecurityEventOrm.occurred_at >= filters.occurred_from
            )
        if filters.occurred_to is not None:
            statement = statement.where(
                SecurityEventOrm.occurred_at <= filters.occurred_to
            )
        rows = (
            self._current.get()
            .scalars(_newest_first(statement, page, SecurityEventOrm))
            .all()
        )
        return build_page(
            [_event_row(row) for row in rows], limit=page.limit, key=lambda r: r.id
        )


def _event_row(row: SecurityEventOrm) -> SecurityEventRow:
    return SecurityEventRow(
        id=row.id,
        event_type=SecurityEventKind(row.event_type),
        severity=SecuritySeverity(row.severity),
        user_id=row.user_id,
        clinic_id=row.clinic_id,
        occurred_at=row.occurred_at,
        ip_truncated=_ip(row.ip_truncated),
    )


@final
class AuditChainRepository(AuditChainPort):
    """Calls the definer ``audit.verify_chain``; it takes the clinic as a parameter."""

    def __init__(self, current: CurrentSession) -> None:
        self._current = current

    @override
    def first_broken_row(self, clinic_id: UUID) -> UUID | None:
        row = (
            self._current.get()
            .execute(FIRST_BROKEN_ROW, {"clinic_id": str(clinic_id)})
            .first()
        )
        return None if row is None else UUID(str(row[0]))
